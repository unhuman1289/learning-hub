import {test} from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import {assignmentSql} from '../lib/daily-sql.ts';
import {berlinDay,cutoffFor,canAdvance} from '../lib/daily-policy.ts';
test('Berlin date and 03:00 cutoff follow winter, summer and DST changes',()=>{
 assert.equal(berlinDay(new Date('2026-10-07T22:30:00Z')),'2026-10-08');
 assert.equal(cutoffFor('2026-01-15'),'2026-01-15T02:00:00.000Z');
 assert.equal(cutoffFor('2026-07-15'),'2026-07-15T01:00:00.000Z');
 assert.equal(cutoffFor('2026-03-29'),'2026-03-29T01:00:00.000Z');
 assert.equal(cutoffFor('2026-10-25'),'2026-10-25T02:00:00.000Z');
 assert.equal(canAdvance({assignedDate:'2026-10-06',completedAt:null},'2026-10-07'),false);
 assert.equal(canAdvance({assignedDate:'2026-10-06',completedAt:'2026-10-07T01:01:00.000Z'},'2026-10-07'),false);
});
test('actual SQLite writer keeps unfinished lessons, advances tracks separately and retains answers',()=>{
 const db=new DatabaseSync(':memory:');
 db.exec(readFileSync(new URL('../drizzle/0001_equal_madame_web.sql',import.meta.url),'utf8'));
 const run=(track,expectedId,day)=>{db.exec('BEGIN');let results;try{results=assignmentSql({track,expectedId,day,id:`daily-${day}-${track}`,content:JSON.stringify({title:'New lesson'}),now:`${day}T01:10:00.000Z`,cutoff:cutoffFor(day)}).map(q=>db.prepare(q.sql).run(...q.args));db.exec('COMMIT');}catch(e){db.exec('ROLLBACK');throw e}return Number(results[1].changes)};
 const current=track=>db.prepare('SELECT l.* FROM learning_slots s JOIN learning_lessons l ON s.lesson_id=l.id WHERE s.track=?').get(track);
 assert.equal(run('Deutsch',null,'2026-10-06'),1);
 assert.equal(run('Cardio',null,'2026-10-06'),1);
 const de=current('Deutsch'),cardio=current('Cardio');
 assert.equal(run('Deutsch',de.id,'2026-10-07'),0);
 assert.deepEqual(current('Deutsch'),de);
 db.prepare('UPDATE learning_lessons SET completed_at=?, response=? WHERE id=?').run('2026-10-06T20:00:00.000Z','Meine Antwort',de.id);
 assert.equal(run('Deutsch',de.id,'2026-10-07'),1);
 assert.equal(run('Cardio',cardio.id,'2026-10-07'),0);
 assert.deepEqual(current('Cardio'),cardio);
 assert.equal(db.prepare('SELECT response FROM learning_lessons WHERE id=?').get(de.id).response,'Meine Antwort');
 assert.equal(run('Deutsch',de.id,'2026-10-07'),0,'stale retries cannot replace the new assignment');
 const fresh=current('Deutsch');
 db.prepare('UPDATE learning_lessons SET completed_at=? WHERE id=?').run('2026-10-07T00:50:00.000Z',fresh.id);
 assert.equal(run('Deutsch',fresh.id,'2026-10-07'),0,'at most one lesson per day');
 db.prepare('UPDATE learning_lessons SET completed_at=NULL WHERE id=?').run(fresh.id);
 assert.equal(run('Deutsch',fresh.id,'2026-10-08'),0,'undo completion is checked by writer');
 db.prepare('UPDATE learning_lessons SET completed_at=? WHERE id=?').run('2026-10-08T01:01:00.000Z',fresh.id);
 assert.equal(run('Deutsch',fresh.id,'2026-10-08'),0,'after 03:00 waits for next day');
 assert.equal(run('Deutsch',fresh.id,'2026-10-09'),1);
 assert.equal(db.prepare('SELECT COUNT(*) n FROM learning_lessons').get().n,4,'no orphan or duplicate lessons');
 db.close();
});
