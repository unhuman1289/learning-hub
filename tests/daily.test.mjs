import {test} from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import {readdirSync} from 'node:fs';
import {assignmentSql} from '../lib/daily-sql.ts';
import {berlinDay,cutoffFor,canAdvance} from '../lib/daily-policy.ts';
test('Berlin date and 03:00 cutoff follow winter, summer and DST changes',()=>{
 assert.equal(berlinDay(new Date('2026-10-07T22:30:00Z')),'2026-10-08');
 assert.equal(cutoffFor('2026-01-15'),'2026-01-15T02:00:00.000Z');
 assert.equal(cutoffFor('2026-07-15'),'2026-07-15T01:00:00.000Z');
 assert.equal(cutoffFor('2026-03-29'),'2026-03-29T01:00:00.000Z');
 assert.equal(cutoffFor('2026-10-25'),'2026-10-25T02:00:00.000Z');
 assert.equal(canAdvance({assignedDate:'2026-10-06',completedAt:null},'2026-10-07'),false);
 assert.equal(canAdvance({assignedDate:'2026-10-06',completedAt:'2026-10-07T01:01:00.000Z'},'2026-10-07'),false);
});
test('actual SQLite writer keeps unfinished lessons, advances tracks separately and retains answers',()=>{
 const db=new DatabaseSync(':memory:');
 for(const file of readdirSync(new URL('../drizzle/',import.meta.url)).filter(f=>f.endsWith('.sql')).sort())db.exec(readFileSync(new URL('../drizzle/'+file,import.meta.url),'utf8'));
 const userA='learner-a',userB='learner-b';
 const run=(userId,track,expectedId,day,id=`les_${userId}_${day}_${track}`)=>{db.exec('BEGIN');let results;try{results=assignmentSql({userId,track,expectedId,day,id,content:JSON.stringify({title:'New lesson'}),now:`${day}T01:10:00.000Z`,cutoff:cutoffFor(day)}).map(q=>db.prepare(q.sql).run(...q.args));db.exec('COMMIT');}catch(e){db.exec('ROLLBACK');throw e}return Number(results[1].changes)};
 const current=(userId,track)=>db.prepare('SELECT l.* FROM learning_slots s JOIN learning_lessons l ON s.user_id=l.user_id AND s.lesson_id=l.id WHERE s.user_id=? AND s.track=?').get(userId,track);
 assert.equal(run(userA,'Deutsch',null,'2026-10-06'),1);
 assert.equal(run(userA,'Cardio',null,'2026-10-06'),1);
 assert.equal(run(userB,'Deutsch',null,'2026-10-06'),1,'another learner can receive the same track and date');
 const de=current(userA,'Deutsch'),cardio=current(userA,'Cardio'),otherDe=current(userB,'Deutsch');
 assert.notEqual(de.id,otherDe.id);
 assert.equal(run(userA,'Deutsch',de.id,'2026-10-07'),0);
 assert.deepEqual(current(userA,'Deutsch'),de);
 db.prepare('UPDATE learning_lessons SET completed_at=?, response=? WHERE user_id=? AND id=?').run('2026-10-06T20:00:00.000Z','Meine Antwort',userA,de.id);
 assert.equal(run(userA,'Deutsch',de.id,'2026-10-07'),1);
 assert.equal(run(userA,'Cardio',cardio.id,'2026-10-07'),0);
 assert.deepEqual(current(userA,'Cardio'),cardio);
 assert.equal(db.prepare('SELECT response FROM learning_lessons WHERE user_id=? AND id=?').get(userA,de.id).response,'Meine Antwort');
 assert.equal(db.prepare('SELECT response FROM learning_lessons WHERE user_id=? AND id=?').get(userB,otherDe.id).response,'');
 assert.equal(run(userA,'Deutsch',de.id,'2026-10-07'),0,'stale retries cannot replace the new assignment');
 const fresh=current(userA,'Deutsch');
 db.prepare('UPDATE learning_lessons SET completed_at=? WHERE user_id=? AND id=?').run('2026-10-07T00:50:00.000Z',userA,fresh.id);
 assert.equal(run(userA,'Deutsch',fresh.id,'2026-10-07'),0,'at most one lesson per day');
 db.prepare('UPDATE learning_lessons SET completed_at=NULL WHERE user_id=? AND id=?').run(userA,fresh.id);
 assert.equal(run(userA,'Deutsch',fresh.id,'2026-10-08'),0,'undo completion is checked by writer');
 db.prepare('UPDATE learning_lessons SET completed_at=? WHERE user_id=? AND id=?').run('2026-10-08T01:01:00.000Z',userA,fresh.id);
 assert.equal(run(userA,'Deutsch',fresh.id,'2026-10-08'),0,'after 03:00 waits for next day');
 assert.equal(run(userA,'Deutsch',fresh.id,'2026-10-09'),1);
 assert.equal(db.prepare('SELECT COUNT(*) n FROM learning_lessons').get().n,5,'each learner retains independent active and historical lessons');
 assert.throws(()=>db.prepare('INSERT INTO learning_lessons (id,user_id,track,payload,assigned_date,updated) VALUES(?,?,?,?,?,?)').run('duplicate-a','learner-a','Deutsch','{}','2026-10-06','now'),/UNIQUE/,'database prevents a second same-track assignment for the same learner/day');
 db.close();
});
